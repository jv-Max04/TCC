"""Construtores puros de figura: arrays entram, `Figure` sai.

O pacote é núcleo puro: não conhece Qt, HTTP, a API, a janela, banco nem disco. O widget que
embute as figuras na janela fica fora daqui. Também não usa o gestor global de figuras do
matplotlib, que num aplicativo com vários painéis deixaria figuras presas no estado global;
cada construtor cria `Figure` e canvas explícitos por `base.nova_figura`, e um teste de direção
de import reprova o contrário.

Os construtores recebem a população inteira. Recorte e amostragem são decisão de quem chama: a
janela manda um resumo pelo fio e o relatório corre no servidor com a matriz toda, e os dois
têm de usar a mesma figura. Toda figura declara na própria imagem o recorte que aplicou e o
método que usou, por um auxiliar só, `recorte.aplica`.

Cor de fundo e escala são do canvas, que pertence ao widget. Os construtores não definem cor
de fundo, de borda nem de texto, e herdam os `rcParams` do momento da construção.
"""

